# 1.3.3 경험치 데이터
def xpList():
    file = (CONFIG_DIR / "xp.txt").open()
    arr = []
    line = file.readline()
    arr.append(line.rstrip('\n'))
    while line:
        try:
            line = file.readline().rstrip('\n')
            arr.append(int(line))
        except:
            break
    file.close()
    return arr


